#!/usr/bin/env bash

set -euo pipefail

module="home/shared/modules/desktop/hypr/default.nix"

grep -F 'configType = "lua"' "$module" >/dev/null || {
  echo 'Hyprland Home Manager module must set configType = "lua".' >&2
  exit 1
}

grep -F 'extraLuaFiles = {' "$module" >/dev/null || {
  echo 'Hyprland Lua modules must be declared through extraLuaFiles.' >&2
  exit 1
}

for mod in monitors startup options binds rules; do
  grep -E "^        ${mod}(\.content)? =" "$module" >/dev/null || {
    echo "extraLuaFiles is missing the ${mod} module" >&2
    exit 1
  }
done

grep -F '"hypr/hyprlock.conf".source' "$module" >/dev/null || {
  echo "Missing XDG config mapping for hypr/hyprlock.conf" >&2
  exit 1
}

# hyprland.lua is generated by the Home Manager module. Installing our own
# entrypoint shadowed that generated file and made Home Manager report that no
# configuration existed.
if grep -F '"hypr/hyprland.lua"' "$module" >/dev/null; then
  echo 'hyprland.lua must not be installed manually; extraLuaFiles generates it.' >&2
  exit 1
fi

for legacy in \
  'hypr/hyprland.conf' \
  'hypr/monitors.conf' \
  'hypr/startup.conf'
do
  if grep -F "\"${legacy}\".source" "$module" >/dev/null; then
    echo "Legacy runtime path still installed: ${legacy}" >&2
    exit 1
  fi
done
